// ---------------------------------------------------------------------------
// Node helpers
// ---------------------------------------------------------------------------

Span span_of(const TSNode& node) {
  Span span;
  const TSPoint start = ts_node_start_point(node);
  span.line = start.row + 1;        // tree-sitter is 0-based
  span.column = start.column + 1;
  span.byte_offset = ts_node_start_byte(node);
  span.byte_length = ts_node_end_byte(node) - ts_node_start_byte(node);
  return span;
}

bool node_is(const TSNode& node, const char* type) {
  return std::strcmp(ts_node_type(node), type) == 0;
}

TSNode field(const TSNode& node, const char* name) {
  return ts_node_child_by_field_name(
      node, name, static_cast<uint32_t>(std::strlen(name)));
}

// Cursor-based iteration over the direct named children of `node` (comments
// are extras and are skipped). `fn` receives each child TSNode.
template <typename Fn>
void each_named_child(const TSNode& node, Fn&& fn) {
  TSTreeCursor cursor = ts_tree_cursor_new(node);
  if (ts_tree_cursor_goto_first_child(&cursor) > 0) {
    do {
      const TSNode child = ts_tree_cursor_current_node(&cursor);
      if (ts_node_is_named(child) && !node_is(child, "comment")) {
        fn(child);
      }
    } while (ts_tree_cursor_goto_next_sibling(&cursor) > 0);
  }
  ts_tree_cursor_delete(&cursor);
}

// ---------------------------------------------------------------------------
// Syntax error collection (cursor DFS; stops descending into ERROR nodes)
// ---------------------------------------------------------------------------

void collect_syntax_errors(const TSNode& node, const std::string& source,
                           std::vector<Diagnostic>& out) {
  if (ts_node_is_error(node) || ts_node_is_missing(node)) {
    Diagnostic diagnostic;
    diagnostic.severity = Severity::kError;
    diagnostic.code = "LP0001";
    diagnostic.span = span_of(node);
    if (ts_node_is_missing(node)) {
      diagnostic.message =
          std::string("syntax error: missing '") + ts_node_type(node) + "'";
    } else {
      const uint32_t start = ts_node_start_byte(node);
      const uint32_t end = ts_node_end_byte(node);
      std::string snippet = source.substr(start, std::min(end - start, 24u));
      if (snippet.empty()) {
        snippet = ts_node_type(node);
      }
      diagnostic.message = "syntax error near '" + snippet + "'";
    }
    out.push_back(std::move(diagnostic));
    return;  // do not descend; one diagnostic per error region
  }
  TSTreeCursor cursor = ts_tree_cursor_new(node);
  if (ts_tree_cursor_goto_first_child(&cursor) > 0) {
    do {
      collect_syntax_errors(ts_tree_cursor_current_node(&cursor), source, out);
    } while (ts_tree_cursor_goto_next_sibling(&cursor) > 0);
  }
  ts_tree_cursor_delete(&cursor);
}

